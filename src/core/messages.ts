/** Pattern translator for the status-bar feedback messages. */
export function translateStatusFor(lang: Language, text: string): string {
  if (lang === "en") return text;
  for (const [re, fn] of STATUS_RULES[lang]) {
    const match = text.match(re);
    if (match) return text.replace(re, fn(match));
  }
  // Fall back to the static chrome dictionary: idle status strings such as the
  // initial "Empty: drop a WAV/OGG file to begin" live there, not in the
  // pattern rules.
  return DICTS[lang][text] ?? text;
}

