/** Every dictionary, keyed by language. English is the identity mapping. */
export const DICTS: Record<Language, Dict> = { en: {}, zh: ZH, ja: JA, ko: KO };

/** Every English key any language knows, used to decide what i18n owns. */
export const KNOWN_KEYS: ReadonlySet<string> = new Set(Object.keys(ZH));

/** Translates one English chrome string into the given language. */
export function translateText(lang: Language, text: string): string {
  return DICTS[lang][text] ?? text;
}

